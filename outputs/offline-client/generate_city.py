"""Generate src/offline/city_data.lua from main_scene_data.lua (main-city buildings).

Fields follow Config.city_data[1].building_list. Re-run after config changes."""
from pathlib import Path
import shutil, subprocess

ROOT = Path(__file__).resolve().parents[2]
PROJ = Path(__file__).resolve().parent
SRC = ROOT / 'outputs/lua-restored-paths/ePoCrKQkWA3vpiOwu2oNfOh02MOeNheW/main_scene_data.lua'
OUT = PROJ / 'src/offline/city_data.lua'

LUA = r'''
setmetatable(_G, {__index = function() return function() return {} end end})
rawset(_G, 'Config', {})
dofile(arg[1])
local c = Config.city_data[1]
local function q(s) return string.format('%q', tostring(s or '')) end
print(string.format('MAP %d %d %d %s', c.width, c.height, c.layer_sum, c.res_id))
local list = {}
for _, b in ipairs(c.building_list) do list[#list + 1] = b end
table.sort(list, function(a, b) return tonumber(a.bid) < tonumber(b.bid) end)
for _, b in ipairs(list) do
    print(string.format('B {bid=%d,name=%s,x=%d,y=%d,layer=%d,res=%s,name_x=%d,name_y=%d,type=%d,dun_id=%d}',
        b.bid, q(b.name), b.x, b.y, b.layer, q(b.res), b.name_x or 0, b.name_y or 0, b.type or 0, b.dun_id or 0))
end
'''

def main():
    luajit = shutil.which('luajit') or str(ROOT / 'work/tools/LuaJIT-2.1/src/luajit')
    script = ROOT / 'work/offline-build/gen_city.lua'
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(LUA)
    r = subprocess.run([luajit, str(script), str(SRC)], capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(r.stderr)
    lines = r.stdout.splitlines()
    w, h, layers, res = lines[0].split()[1:]
    rows = [l[2:] + ',' for l in lines if l.startswith('B ')]
    text = ['-- Generated by generate_city.py from main_scene_data.lua; edit the generator.',
            'return {', f'width={w}, height={h}, layers={layers}, res_id="{res}",', 'buildings = {'] + rows + ['},', '}']
    OUT.write_text('\n'.join(text) + '\n', encoding='utf-8')
    print(f'buildings={len(rows)} -> {OUT}')

if __name__ == '__main__':
    main()
