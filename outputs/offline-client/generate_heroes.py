"""Generate src/offline/hero_data.lua (presentation subset of partner_data.lua).

Reads the recovered config with luajit (declarations only; no game code runs) and
writes a compact table of heroes + hero-library text. Re-run after config changes.
Field meanings follow Config.PartnerData.data_partner_base / data_partner_library.
"""
from pathlib import Path
import shutil, subprocess

ROOT = Path(__file__).resolve().parents[2]
PROJ = Path(__file__).resolve().parent
SRC = ROOT / 'outputs/lua-restored-paths/ePoCrKQkWA3vpiOwu2oNfOh02MOeNheW/partner_data.lua'
OUT = PROJ / 'src/offline/hero_data.lua'

LUA = r'''
local P, OUT = arg[1], arg[2]
TI18N = function(s) return s end
setmetatable(_G, {__index = function() return function() return {} end end})
rawset(_G, 'Config', {})
dofile(P)
local D = Config.PartnerData
local function q(s) return string.format('%q', tostring(s or '')):gsub('\\\n', '\\n') end
local bids = {}
for bid in pairs(D.data_partner_base) do bids[#bids + 1] = bid end
table.sort(bids)
local out = {'-- Generated by generate_heroes.py from partner_data.lua; edit the generator, not this file.\n',
    'return {\nheroes = {\n'}
for _, bid in ipairs(bids) do
    local h = D.data_partner_base[bid]
    out[#out + 1] = string.format(
        '[%d]={bid=%d,name=%s,camp=%d,type=%d,star=%d,lev_limit=%d,show_order=%d,pos_type=%d,hero_pos=%s,intro=%s,item_id=%d,rare=%d,break_id=%d},\n',
        bid, bid, q(h.name), h.camp_type or 0, h.type or 0, h.init_star or 0, h.cystal_lev_limit or 0,
        h.show_order or 0, h.pos_type or 0, q(h.hero_pos), q(h.introduce_str), h.item_id or 0, h.rare_flag or 0, h.break_id or 0)
end
out[#out + 1] = '},\nlibrary = {\n'
local lib = {}
for key, row in pairs(D.data_partner_library_table) do
    local ok, v = pcall(function() return loadstring('return ' .. row)() end)
    if ok and type(v) == 'table' then lib[#lib + 1] = v end
end
table.sort(lib, function(a, b) return a[1] < b[1] end)
for _, v in ipairs(lib) do
    local has_art = (v[5] and #v[5] > 0 and (v[6] or 0) > 0) and 'true' or 'false'
    out[#out + 1] = string.format('[%d]={title=%s,voice=%s,story=%s,has_art=%s},\n', v[1], q(v[2]), q(v[3]), q(v[4]), has_art)
end
out[#out + 1] = '},\n}\n'
local f = assert(io.open(OUT, 'w')); f:write(table.concat(out)); f:close()
print('heroes ' .. #bids .. ' library ' .. #lib)
'''

def main():
    luajit = shutil.which('luajit') or str(ROOT / 'work/tools/LuaJIT-2.1/src/luajit')
    script = PROJ.parent.parent / 'work/offline-build/gen_heroes.lua'
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(LUA)
    r = subprocess.run([luajit, str(script), str(SRC), str(OUT)], capture_output=True, text=True)
    print(r.stdout.strip() or r.stderr.strip())
    if r.returncode:
        raise SystemExit(r.returncode)

if __name__ == '__main__':
    main()
