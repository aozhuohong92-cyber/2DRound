"""Generate src/offline/hero_data.lua (presentation subset of partner_data.lua).

Reads the recovered config with luajit (declarations only; no game code runs) and
writes a compact table of heroes + hero-library text. Re-run after config changes.
Field meanings follow Config.PartnerData.data_partner_base / data_partner_library.
"""
from pathlib import Path
import shutil, subprocess

ROOT = Path(__file__).resolve().parents[2]
PROJ = Path(__file__).resolve().parent
SRC = ROOT / 'outputs/lua-restored-paths/ePoCrKQkWA3vpiOwu2oNfOh02MOeNheW/partner_data.lua'
OUT = PROJ / 'src/offline/hero_data.lua'
OUT_EXTRA = PROJ / 'src/offline/hero_extra_data.lua'
OUT_STATS = PROJ / 'src/offline/hero_stats_data.lua'
CFG_DIR = SRC.parent

LUA = r'''
local P, OUT, OUT_EXTRA, DIR, OUT_STATS = arg[1], arg[2], arg[3], arg[4], arg[5]
TI18N = function(s) return s end
setmetatable(_G, {__index = function() return function() return {} end end})
rawset(_G, 'Config', {})
dofile(P)
local D = Config.PartnerData
local function q(s) return string.format('%q', tostring(s or '')):gsub('\\\n', '\\n') end
local bids = {}
for bid in pairs(D.data_partner_base) do bids[#bids + 1] = bid end
table.sort(bids)
local out = {'-- Generated by generate_heroes.py from partner_data.lua; edit the generator, not this file.\n',
    'return {\nheroes = {\n'}
for _, bid in ipairs(bids) do
    local h = D.data_partner_base[bid]
    out[#out + 1] = string.format(
        '[%d]={bid=%d,name=%s,camp=%d,type=%d,star=%d,lev_limit=%d,show_order=%d,pos_type=%d,hero_pos=%s,intro=%s,item_id=%d,rare=%d,break_id=%d},\n',
        bid, bid, q(h.name), h.camp_type or 0, h.type or 0, h.init_star or 0, h.cystal_lev_limit or 0,
        h.show_order or 0, h.pos_type or 0, q(h.hero_pos), q(h.introduce_str), h.item_id or 0, h.rare_flag or 0, h.break_id or 0)
end
out[#out + 1] = '},\nlibrary = {\n'
local lib = {}
for key, row in pairs(D.data_partner_library_table) do
    local ok, v = pcall(function() return loadstring('return ' .. row)() end)
    if ok and type(v) == 'table' then lib[#lib + 1] = v end
end
table.sort(lib, function(a, b) return a[1] < b[1] end)
for _, v in ipairs(lib) do
    local has_art = (v[5] and #v[5] > 0 and (v[6] or 0) > 0) and 'true' or 'false'
    out[#out + 1] = string.format('[%d]={title=%s,voice=%s,story=%s,has_art=%s},\n', v[1], q(v[2]), q(v[3]), q(v[4]), has_art)
end
out[#out + 1] = '},\n}\n'
local f = assert(io.open(OUT, 'w')); f:write(table.concat(out)); f:close()
print('heroes ' .. #bids .. ' library ' .. #lib)

-- Hero detail (图鉴 single-hero panel): attributes per (bid, star) from data_partner_show,
-- model/skills from data_partner_star, skill names, and the power weights.
dofile(DIR .. '/attr_data.lua')
dofile(DIR .. '/skill_data.lua')
for i = 1, 6 do pcall(dofile, DIR .. '/skill_data' .. i .. '.lua') end
local show = D.data_partner_show_table
local star = D.data_partner_star_table
local keys = {}
for k in pairs(show) do keys[#keys + 1] = k end
table.sort(keys)
local function parse(row) local ok, v = pcall(function() return loadstring('return ' .. row)() end); return ok and v or nil end
local st = {'-- Generated by generate_heroes.py (partner_data.lua, skill_data*.lua, attr_data.lua); edit the generator.\nreturn {\nrows = {\n'}
local skill_ids, seen = {}, {}
local ATTR = {'atk', 'def', 'hp', 'speed', 'crit_rate', 'crit_ratio', 'hit_magic', 'dodge_magic', 'tenacity',
              'hit_rate', 'res', 'dodge_rate', 'cure', 'be_cure', 'dam'}
for _, key in ipairs(keys) do
    local r = parse(show[key])
    local s2 = star[key] and parse(star[key]) or nil
    if r and #r >= 18 then
        local vals = {}
        for i, name in ipairs(ATTR) do vals[#vals + 1] = string.format('%s=%d', name, r[3 + i] or 0) end
        local skills = {}
        for _, sk in ipairs(s2 and s2[14] or {}) do
            skills[#skills + 1] = tostring(sk[2])
            if not seen[sk[2]] then seen[sk[2]] = true; skill_ids[#skill_ids + 1] = sk[2] end
        end
        st[#st + 1] = string.format('[%q]={bid=%d,lev=%d,star=%d,%s,model=%q,lev_max=%d,skills={%s}},\n',
            key, r[1], r[2], r[3], table.concat(vals, ','), s2 and tostring(s2[3]) or '', s2 and s2[15] or r[2], table.concat(skills, ','))
    end
end
st[#st + 1] = '},\nskills = {\n'
table.sort(skill_ids)
local skill_table = {}
for i = 1, 6 do
    local t = Config['SkillData' .. i] and Config['SkillData' .. i].data_get_skill_table
    if t then for k, v in pairs(t) do skill_table[tonumber(k)] = v end end
end
local nskill = 0
for _, id in ipairs(skill_ids) do
    local sk = skill_table[id] and parse(skill_table[id])
    if sk then
        nskill = nskill + 1
        st[#st + 1] = string.format('[%d]={name=%s,level=%d,normal=%d,icon=%s},\n', id, q(sk[2]), sk[6] or 1, sk[7] or 0, q(sk[20]))
    end
end
st[#st + 1] = '},\npower = {\n'
local pk = {}
for k, v in pairs(Config.AttrData.data_power) do if (v.power or 0) ~= 0 then pk[#pk + 1] = k end end
table.sort(pk)
for _, k in ipairs(pk) do
    st[#st + 1] = string.format('%s={%d,%d},\n', k, Config.AttrData.data_power[k].power, Config.AttrData.data_power[k].not_to_power or 0)
end
st[#st + 1] = '},\n}\n'
local fh = assert(io.open(OUT_STATS, 'w')); fh:write(table.concat(st)); fh:close()
print('stats rows ' .. #keys .. ' skills ' .. nskill .. ' power keys ' .. #pk)

-- Ghost (elfin/sprite) hatch slots and belief (halidom) entries for the 幽灵 / 信念 tabs.
dofile(DIR .. '/halidom_data.lua')
dofile(DIR .. '/sprite_data.lua')
local ex = {'-- Generated by generate_heroes.py from halidom_data.lua / sprite_data.lua; edit the generator.\nreturn {\n'}
ex[#ex + 1] = 'belief = {\n'
for _, row in ipairs(Config.HalidomData.data_base) do
    local loss = row.loss and row.loss[1] or {}
    ex[#ex + 1] = string.format('{id=%d,camp=%d,name=%s,desc=%s,lock_desc=%s,need_camp=%d,need_star=%d,need_num=%d},\n',
        tonumber(row.id), tonumber(row.camp), q(row.name), q(row.desc), q(row.lock_desc),
        tonumber(loss[1]) or 0, tonumber(loss[2]) or 0, tonumber(loss[3]) or 0)
end
ex[#ex + 1] = '},\nghost_slots = {\n'
local slots = {}
for _, row in ipairs(Config.SpriteData.data_hatch_data) do slots[#slots + 1] = row end
table.sort(slots, function(a, b) return tonumber(a.sort) < tonumber(b.sort) end)
for _, row in ipairs(slots) do
    local cond = row.hatch_cond or {}
    local val = cond[2]
    if type(val) == 'table' then val = #val end
    local cost = row.expend and row.expend[1] and row.expend[1][2] or 0
    ex[#ex + 1] = string.format('{sort=%d,name=%s,lock=%s,tip=%s,cond=%s,value=%d,cost=%d},\n',
        tonumber(row.sort), q(row.name), q(row.desc1), q(row.desc2), q(cond[1]), tonumber(val) or 0, tonumber(cost) or 0)
end
ex[#ex + 1] = '},\nrule = ' .. q(Config.HalidomData.data_const.halidom_rule.desc) .. ',\n}\n'
local g = assert(io.open(OUT_EXTRA, 'w')); g:write(table.concat(ex)); g:close()
print('belief ' .. #Config.HalidomData.data_base .. ' ghost_slots ' .. #slots)
'''

def main():
    luajit = shutil.which('luajit') or str(ROOT / 'work/tools/LuaJIT-2.1/src/luajit')
    script = PROJ.parent.parent / 'work/offline-build/gen_heroes.lua'
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(LUA)
    r = subprocess.run([luajit, str(script), str(SRC), str(OUT), str(OUT_EXTRA), str(CFG_DIR), str(OUT_STATS)],
                       capture_output=True, text=True)
    print(r.stdout.strip() or r.stderr.strip())
    if r.returncode:
        raise SystemExit(r.returncode)

if __name__ == '__main__':
    main()
