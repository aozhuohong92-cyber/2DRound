"""Generate src/offline/exercise_data.lua (历练 / 海贼试炼 window data).

Source: Config.DailyplayData.data_exerciseactivity (dailyplay_data.lua) and item names from
item_data*.lua. Re-run after config changes; do not edit the generated file by hand.
"""
from pathlib import Path
import re, shutil, subprocess

ROOT = Path(__file__).resolve().parents[2]
PROJ = Path(__file__).resolve().parent
CFG = ROOT / 'outputs/lua-restored-paths/ePoCrKQkWA3vpiOwu2oNfOh02MOeNheW'
OUT = PROJ / 'src/offline/exercise_data.lua'

LUA = r'''
TI18N = function(s) return s end
setmetatable(_G, {__index = function() return function() return {} end end})
rawset(_G, 'Config', {})
dofile(arg[1])
local function q(s) return string.format('%q', tostring(s or '')):gsub('\\\n', '\\n') end
local out = {}
for _, row in ipairs(Config.DailyplayData.data_exerciseactivity) do
    local items = {}
    for _, id in ipairs(row.val and row.val[1] or {}) do items[#items + 1] = tostring(id) end
    local lev = 0
    for _, cond in ipairs(row.activate or {}) do
        if cond[1] == 'lev' then lev = tonumber(cond[2]) or 0 end
    end
    out[#out + 1] = string.format('{id=%d,name=%s,goto_id=%d,is_open=%d,lock_desc=%s,desc=%s,pic=%s,lev=%d,items={%s}}',
        tonumber(row.id), q(row.name), tonumber(row.goto_id) or 0, tonumber(row.is_open) or 0,
        q(row.lock_desc), q(row.desc), q(row.pic_name), lev, table.concat(items, ','))
end
print(table.concat(out, '\n'))
'''

def main():
    luajit = shutil.which('luajit') or str(ROOT / 'work/tools/LuaJIT-2.1/src/luajit')
    script = ROOT / 'work/offline-build/gen_exercise.lua'
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(LUA)
    r = subprocess.run([luajit, str(script), str(CFG / 'dailyplay_data.lua')], capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(r.stderr)
    rows = [l for l in r.stdout.splitlines() if l.startswith('{id=')]
    ids = sorted({int(i) for row in rows for i in re.findall(r'items=\{([^}]*)\}', row)[0].split(',') if i})
    text = ''.join(p.read_text(encoding='utf-8', errors='ignore') for p in CFG.glob('item_data*.lua'))
    names = {}
    for i in ids:
        m = re.search(r'\[%d\.0\] = "\{%d, \\"([^"\\]+)\\", (\d+),' % (i, i), text)
        if m:
            names[i] = (m.group(1), int(m.group(2)))
    lines = ['-- Generated by generate_exercise.py from dailyplay_data.lua / item_data*.lua; edit the generator.',
             'return {', 'activities = {']
    lines += [row + ',' for row in rows]
    lines += ['},', 'items = {']
    for i in ids:
        name, icon = names.get(i, ('', i))
        lines.append('[%d]={name=%s,icon=%d},' % (i, '"%s"' % name, icon))
    lines += ['},', '}']
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'activities={len(rows)} items={len(ids)} -> {OUT}')

if __name__ == '__main__':
    main()
