function Config.HomeData.data_home_unit(slot0)
	if Config.HomeData.data_home_unit_cache[slot0] == nil then
		if not Config.HomeData.data_home_unit_table[slot0] then
			return
		end

		if not loadstring(string.format("return %s", slot1))() then
			return
		end

		Config.HomeData.data_home_unit_cache[slot0] = {
			bid = slot1[1],
			name = slot1[2],
			soft = slot1[3],
			set_id = slot1[4],
			tile_list_1 = slot1[5],
			tile_list_2 = slot1[6],
			offset_1 = slot1[7],
			offset_2 = slot1[8],
			type = slot1[9],
			dir = slot1[10],
			desc = slot1[11],
			res = slot1[12],
			icon = slot1[13],
			grid_desc = slot1[14],
			effect_count = slot1[15],
			soruce_id = slot1[16]
		}
	end

	return Config.HomeData.data_home_unit_cache[slot0]
end

